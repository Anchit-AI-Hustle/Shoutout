// Supabase "Send SMS Hook" — https://supabase.com/docs/guides/auth/auth-hooks/send-sms-hook
//
// Supabase Auth calls this function instead of its own built-in SMS
// sending (Twilio/MessageBird/Vonage/TextLocal) whenever a phone-OTP is
// requested or verified. It POSTs a signed webhook payload shaped like
// { user: {...}, sms: { otp: "561166" } }; this function's only job is to
// verify that signature, then hand the phone + OTP to MSG91 for delivery.
// No output is required on success — an empty 200 response is enough.
//
// Deployed with verify_jwt = false (deliberately, matching the tool's own
// guidance: only disable JWT verification when the function implements its
// own auth). Supabase Auth doesn't send a user JWT to this hook — it signs
// the payload with SEND_SMS_HOOK_SECRET instead, verified below via
// standardwebhooks. That signature check IS the authentication for this
// endpoint; there is no other gate.
//
// MSG91 integration, not Twilio: docs/CLAUDE.md's "SHOUTOUT" project is
// India-only, and MSG91's Flow API is built around India's DLT
// (Distributed Ledger Technology) sender-ID/template registration that
// TRAI requires for commercial SMS — Twilio doesn't handle that
// registration, and Indian carriers can silently filter unregistered
// senders. This targets MSG91's Flow API v5 as publicly documented; I
// don't have a way to check that surface against a live account from
// here, so verify the exact response shape (the `type` field check below)
// against your own account's API docs/Postman collection once you have
// real credentials, before relying on this in production.
//
// Required secrets (Supabase Dashboard → Project Settings → Edge Functions
// → Secrets, or `supabase secrets set`):
//   SEND_SMS_HOOK_SECRET — generated by Supabase when you enable this hook
//                          under Authentication → Hooks → Send SMS hook
//   MSG91_AUTH_KEY        — from the MSG91 dashboard (API Keys)
//   MSG91_TEMPLATE_ID     — the DLT-approved template's ID (MSG91 dashboard
//                          → Campaigns/OTP → Templates). The template's
//                          message body must contain exactly one variable
//                          for the OTP — e.g. "Your ShoutOut OTP is ##OTP##.
//                          Valid for 5 minutes. Do not share it."
//   MSG91_OTP_VAR_NAME    — the variable name used in that template
//                          (defaults to "OTP" below — MSG91 lets you name
//                          it anything when you create the template, so
//                          this must match exactly what you chose there)

import { Webhook } from 'https://esm.sh/standardwebhooks@1.0.0';

const MSG91_AUTH_KEY = Deno.env.get('MSG91_AUTH_KEY');
const MSG91_TEMPLATE_ID = Deno.env.get('MSG91_TEMPLATE_ID');
const MSG91_OTP_VAR_NAME = Deno.env.get('MSG91_OTP_VAR_NAME') ?? 'OTP';
const SEND_SMS_HOOK_SECRET = Deno.env.get('SEND_SMS_HOOK_SECRET');

interface Msg91Response {
  type?: string;
  message?: string;
}

// MSG91 wants the number without a leading '+' (e.g. "919876543210").
// Supabase's user.phone is E.164 with the '+' ("+919876543210").
function toMsg91Mobile(e164Phone: string): string {
  return e164Phone.replace(/^\+/, '');
}

async function sendViaMsg91(phone: string, otp: string): Promise<Msg91Response> {
  if (!MSG91_AUTH_KEY || !MSG91_TEMPLATE_ID) {
    throw new Error('MSG91_AUTH_KEY or MSG91_TEMPLATE_ID is not configured');
  }

  const response = await fetch('https://control.msg91.com/api/v5/flow/', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      authkey: MSG91_AUTH_KEY,
    },
    body: JSON.stringify({
      template_id: MSG91_TEMPLATE_ID,
      short_url: '0',
      recipients: [
        {
          mobiles: toMsg91Mobile(phone),
          [MSG91_OTP_VAR_NAME]: otp,
        },
      ],
    }),
  });

  return (await response.json()) as Msg91Response;
}

Deno.serve(async (req) => {
  if (!SEND_SMS_HOOK_SECRET) {
    return new Response(
      JSON.stringify({
        error: { http_code: 500, message: 'SEND_SMS_HOOK_SECRET is not configured' },
      }),
      { status: 500, headers: { 'Content-Type': 'application/json' } },
    );
  }

  const payload = await req.text();
  const headers = Object.fromEntries(req.headers);
  // Supabase prefixes the secret with "v1,whsec_"; standardwebhooks wants
  // the raw base64 secret without that prefix.
  const base64Secret = SEND_SMS_HOOK_SECRET.replace('v1,whsec_', '');
  const wh = new Webhook(base64Secret);

  try {
    const { user, sms } = wh.verify(payload, headers) as {
      user: { phone: string };
      sms: { otp: string };
    };

    const result = await sendViaMsg91(user.phone, sms.otp);

    if (result.type !== 'success') {
      return new Response(
        JSON.stringify({
          error: {
            http_code: 502,
            message: `MSG91 send failed: ${result.message ?? 'unknown error'}`,
          },
        }),
        { status: 502, headers: { 'Content-Type': 'application/json' } },
      );
    }

    return new Response(JSON.stringify({}), {
      status: 200,
      headers: { 'Content-Type': 'application/json' },
    });
  } catch (error) {
    return new Response(
      JSON.stringify({
        error: { http_code: 500, message: `Failed to send SMS: ${String(error)}` },
      }),
      { status: 500, headers: { 'Content-Type': 'application/json' } },
    );
  }
});
